/**
 * 「Heming」单线手写字形 —— 全项目唯一真源。
 *
 * 为什么是手绘 path 而不是手写字体：
 * - 项目无任何字体文件与字体配置，引入手写字体要处理授权、自托管与子集化；
 *   桌面端 splash.html 还要求自包含（内联 base64 会把文件撑大）。
 * - 只有逐笔描边（stroke-dashoffset）是真的在「写」；用字体只能做擦除式显现，观感差一档。
 * - 与既有视觉语言一致：项目图标一律细线墨色 SVG，单线手写是同一套语言。
 *
 * 坐标系：viewBox 0 0 400 150，内容居中（bbox x 44–355 / y 23–127）。
 * 基线 y≈101，x-height 顶 y≈59（e/m/n 的顶都齐这条线），上伸 y≈23，下伸 y≈127。
 * 笔画顺序 = 真实书写顺序（H 左竖→右竖→横；m/n 一笔写完；i 的点最后落）。
 *
 * 两个易错点（改字形前先读，两个都踩过）：
 * - **e 必须右下开口**：上环（眼）闭合，但右腰要在中横与底部起笔之间留空。
 *   右腰一旦上下连通，整字就成了「8」。
 * - **m/n 的肩要够圆**：肩从 y≈73 起弧、顶点 y≈59（占字高约 1/3）。
 *   肩太浅（比如只抬高 7 单位）会变成竖笔上的小凸起，看着像栅栏。
 *
 * 坐标一律用绝对命令（M/L/C）—— 书写动效与测试的坐标解析都依赖这一点。
 *
 * ⚠ 改这里的 path 数据必须同步改 packages/desktop/splash.html 的内嵌副本，
 * `packages/desktop/wordmark-drift.test.js` 会断言两者逐字节一致。
 */

